"""Generate a PDF of assignment instructions for offline use.

Uses fpdf2 (pure-Python, no system dependencies).
"""

from __future__ import annotations

import io
import re
from datetime import datetime, timezone

from fpdf import FPDF


_BRAND_COLOR = (25, 62, 116)  # #193E74
_TEXT_COLOR = (26, 26, 26)


class _AssignmentPDF(FPDF):
    """Branded single-assignment PDF."""

    def __init__(self, course_title: str) -> None:
        super().__init__()
        self._course_title = course_title

    def header(self) -> None:
        self.set_font("Helvetica", "B", 10)
        self.set_text_color(*_BRAND_COLOR)
        self.cell(0, 8, "Marconi Elearn", ln=False, align="L")
        self.set_font("Helvetica", "", 9)
        self.set_text_color(100, 100, 100)
        self.cell(0, 8, self._course_title, ln=True, align="R")
        self.set_draw_color(*_BRAND_COLOR)
        self.set_line_width(0.5)
        self.line(10, self.get_y(), self.w - 10, self.get_y())
        self.ln(4)

    def footer(self) -> None:
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(150, 150, 150)
        self.cell(0, 10, f"Page {self.page_no()}", align="C")


def _strip_html(text: str) -> str:
    """Very basic HTML tag stripper for assignment descriptions."""
    text = re.sub(r"<br\s*/?>", "\n", text, flags=re.IGNORECASE)
    text = re.sub(r"<p[^>]*>", "\n", text, flags=re.IGNORECASE)
    text = re.sub(r"</p>", "\n", text, flags=re.IGNORECASE)
    text = re.sub(r"<li[^>]*>", "\n  - ", text, flags=re.IGNORECASE)
    text = re.sub(r"<[^>]+>", "", text)
    text = text.replace("&amp;", "&")
    text = text.replace("&lt;", "<")
    text = text.replace("&gt;", ">")
    text = text.replace("&quot;", '"')
    text = text.replace("&#39;", "'")
    text = text.replace("&nbsp;", " ")
    return text.strip()


def generate_assignment_pdf(
    *,
    course_title: str,
    course_code: str,
    assignment_title: str,
    description: str | None,
    due_date: datetime | None,
    max_points: int | None,
) -> bytes:
    """Return PDF bytes for one assignment's instructions."""
    pdf = _AssignmentPDF(course_title=f"{course_code} - {course_title}")
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.add_page()

    pdf.set_font("Helvetica", "B", 18)
    pdf.set_text_color(*_BRAND_COLOR)
    pdf.multi_cell(0, 10, assignment_title, align="L")
    pdf.ln(2)

    meta_parts: list[str] = []
    if due_date is not None:
        due_utc = due_date.astimezone(timezone.utc) if due_date.tzinfo else due_date
        meta_parts.append(f"Due: {due_utc.strftime('%b %d, %Y at %I:%M %p UTC')}")
    if max_points is not None:
        meta_parts.append(f"Max Points: {max_points}")
    if meta_parts:
        pdf.set_font("Helvetica", "", 10)
        pdf.set_text_color(100, 100, 100)
        pdf.cell(0, 7, "  |  ".join(meta_parts), ln=True)
        pdf.ln(4)

    pdf.set_draw_color(200, 200, 200)
    pdf.set_line_width(0.3)
    pdf.line(10, pdf.get_y(), pdf.w - 10, pdf.get_y())
    pdf.ln(6)

    pdf.set_font("Helvetica", "", 11)
    pdf.set_text_color(*_TEXT_COLOR)
    if description:
        clean = _strip_html(description)
        pdf.multi_cell(0, 6, clean)
    else:
        pdf.set_text_color(150, 150, 150)
        pdf.cell(0, 10, "No description provided.", ln=True)

    pdf.ln(12)
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(150, 150, 150)
    pdf.cell(
        0,
        6,
        f"Generated by Marconi Elearn on {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}",
        ln=True,
        align="R",
    )

    buf = io.BytesIO()
    pdf.output(buf)
    return buf.getvalue()
